export function getPlayersByFranchiseAndDecade(franchise: string, decade: string): Player[] {
  return ALL_PLAYERS.filter(p => p.team === franchise && p.decade === decade);
}

export function getPlayersByDecade(decade: string): Player[] {
  return ALL_PLAYERS.filter(p => p.decade === decade);
}

export function getPlayersByFranchise(franchise: string): Player[] {
  return ALL_PLAYERS.filter(p => p.team === franchise);
}

export function getPlayersByPosition(position: Position): Player[] {
  return ALL_PLAYERS.filter(p => p.position === position);
}

export function getPlayerById(id: string): Player | undefined {
  return ALL_PLAYERS.find(p => p.id === id);
}

export function getRandomPlayersByFranchiseAndDecade(
  franchise: string,
  decade: string,
  count: number = 5
): Player[] {
  const pool = getPlayersByFranchiseAndDecade(franchise, decade);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}