export function getRandomPlayersByFranchiseAndDecade(
  franchise: string,
  decade: string,
  count: number = 5
): Player[] {
  const safeCount = Number.isInteger(count) ? Math.max(1, Math.min(count, 25)) : 5;
  const pool = getPlayersByFranchiseAndDecade(franchise, decade);
  const shuffled = fisherYatesShuffle(pool);
  return shuffled.slice(0, safeCount);
}